//! Development-only generator; not linked into the gateway binary.
use std::{fmt::Write as _, fs, path::PathBuf};

use anyhow::Result;
use estuary::{
    config::{
        ModelCapabilityConfig, NodeConfig, ProviderConfig, ProviderKind, VllmKvEventsConfig,
        contract::{
            IntegerBounds, NodeIntegerLimits, RESERVED_UPSTREAM_HEADERS, editor_node_defaults,
            js_integer_limits,
        },
    },
    node::{
        CircuitState, EngineTelemetry, HealthState, LifecycleState, NodeSnapshot, ProviderState,
    },
    observability::{
        Counts, Distribution, Peaks, Point, Pressure, Rate, Rates, ScopeSnapshot, Snapshot,
    },
    session_log::{
        AttemptRecord, LogEvent, LogStatus, PayloadDetail, RequestDetail, RequestPage,
        RequestRecord, SessionSummary,
    },
};
use serde::Serialize;
use ts_rs::{Config, TS};

#[derive(Serialize, TS)]
struct ConfigDefaults {
    node: NodeConfig,
    editor: NodeConfig,
    capability: ModelCapabilityConfig,
    kv_events: VllmKvEventsConfig,
}

fn main() -> Result<()> {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let out = std::env::args_os()
        .nth(1)
        .map_or_else(|| root.join("web/src/generated"), PathBuf::from);
    fs::create_dir_all(&out)?;
    let config = Config::new().with_large_int("number");
    let mut output = String::from(
        "// Generated by cargo run --features config-contract --example config_contract. Do not edit.\n\n",
    );
    macro_rules! export {
        ($($ty:ty),+ $(,)?) => { $(writeln!(output, "export {}\n", <$ty>::decl(&config))?;)+ };
    }
    export!(
        NodeConfig,
        ProviderConfig,
        ModelCapabilityConfig,
        ProviderKind,
        VllmKvEventsConfig,
        IntegerBounds,
        NodeIntegerLimits,
        ConfigDefaults,
        HealthState,
        ProviderState,
        LifecycleState,
        CircuitState,
        EngineTelemetry,
        NodeSnapshot,
        Counts,
        Distribution,
        Rate,
        Rates,
        Pressure,
        Peaks,
        Point,
        ScopeSnapshot,
        Snapshot,
        AttemptRecord,
        LogEvent,
        LogStatus,
        PayloadDetail,
        RequestDetail,
        RequestPage,
        RequestRecord,
        SessionSummary,
    );
    let defaults = ConfigDefaults {
        node: NodeConfig::default(),
        editor: editor_node_defaults(),
        capability: ModelCapabilityConfig::default(),
        kv_events: VllmKvEventsConfig::default(),
    };
    writeln!(
        output,
        "export const configDefaults: ConfigDefaults = {};\n",
        serde_json::to_string_pretty(&defaults)?
    )?;
    writeln!(
        output,
        "export const NODE_INTEGER_LIMITS: NodeIntegerLimits = {};\n",
        serde_json::to_string_pretty(&js_integer_limits())?
    )?;
    writeln!(
        output,
        "export const RESERVED_UPSTREAM_HEADERS: readonly string[] = {};",
        serde_json::to_string_pretty(RESERVED_UPSTREAM_HEADERS)?
    )?;
    fs::write(out.join("config.ts"), output)?;
    Ok(())
}
